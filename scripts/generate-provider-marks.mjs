#!/usr/bin/env node
/**
 * Generates `src/components/os/provider-marks.tsx` from simple-icons.
 *
 * The brand marks are copied into the repo at build-author time rather than
 * imported at runtime: simple-icons is ~4 MB of SVG paths and the app needs
 * five of them. Marks simple-icons does not carry (Slack dropped its icon
 * from the set; Aeries and Wilcox were never in it) are hand-drawn below.
 *
 *   bun run marks
 */

import { writeFileSync } from "node:fs";
import * as icons from "simple-icons";

const PICK = [
  ["googleclassroom", "siGoogleclassroom"],
  ["googlecalendar", "siGooglecalendar"],
  ["gmail", "siGmail"],
  ["github", "siGithub"],
  ["notion", "siNotion"],
];

const generated = PICK.map(([key, name]) => {
  const icon = icons[name];
  if (!icon) throw new Error(`simple-icons has no ${name}`);
  // Black marks follow the text colour so they read in dark mode.
  const mono = icon.hex === "000000" || icon.hex === "181717";
  return `  ${key}: { title: ${JSON.stringify(icon.title)}, hex: ${JSON.stringify(mono ? null : `#${icon.hex}`)}, path: ${JSON.stringify(icon.path)} },`;
}).join("\n");

const file = `/**
 * Provider marks. GENERATED by scripts/generate-provider-marks.mjs — do not
 * edit the \`SIMPLE\` block by hand; run \`bun run marks\` instead.
 *
 * Each mark is drawn on a 24-unit grid. Brand colours come from simple-icons;
 * marks whose brand colour is black (GitHub, Notion) use \`currentColor\` so
 * they stay visible on a dark background.
 */

import { cn } from "@/lib/utils";

export type ProviderMarkId =
  | "googleclassroom"
  | "googlecalendar"
  | "gmail"
  | "github"
  | "notion"
  | "slack"
  | "aeries"
  | "wilcox"
  | "weather"
  | "openai";

interface SimpleMark {
  title: string;
  hex: string | null;
  path: string;
}

const SIMPLE: Record<"googleclassroom" | "googlecalendar" | "gmail" | "github" | "notion", SimpleMark> = {
${generated}
};

const SLACK = [
  ["#E01E5A", "M5.04 15.16a2.52 2.52 0 1 1-2.52-2.52h2.52v2.52Zm1.27 0a2.52 2.52 0 1 1 5.04 0v6.3a2.52 2.52 0 1 1-5.04 0v-6.3Z"],
  ["#36C5F0", "M8.83 5.04a2.52 2.52 0 1 1 2.52-2.52v2.52H8.83Zm0 1.27a2.52 2.52 0 1 1 0 5.04h-6.3a2.52 2.52 0 1 1 0-5.04h6.3Z"],
  ["#2EB67D", "M18.96 8.83a2.52 2.52 0 1 1 2.52 2.52h-2.52V8.83Zm-1.27 0a2.52 2.52 0 1 1-5.04 0v-6.3a2.52 2.52 0 1 1 5.04 0v6.3Z"],
  ["#ECB22E", "M15.16 18.96a2.52 2.52 0 1 1-2.52 2.52v-2.52h2.52Zm0-1.27a2.52 2.52 0 1 1 0-5.04h6.3a2.52 2.52 0 1 1 0 5.04h-6.3Z"],
];

export function ProviderMark({
  id,
  className,
  mono = false,
}: {
  id: ProviderMarkId;
  className?: string | undefined;
  /** Draw in the current text colour instead of the brand colour. */
  mono?: boolean | undefined;
}) {
  const cls = cn("size-5 shrink-0", className);

  if (id in SIMPLE) {
    const mark = SIMPLE[id as keyof typeof SIMPLE];
    return (
      <svg viewBox="0 0 24 24" role="img" aria-label={mark.title} className={cls}>
        <path d={mark.path} fill={mono || !mark.hex ? "currentColor" : mark.hex} />
      </svg>
    );
  }

  switch (id) {
    case "slack":
      return (
        <svg viewBox="0 0 24 24" role="img" aria-label="Slack" className={cls}>
          {SLACK.map(([fill, d]) => (
            <path key={d} d={d} fill={mono ? "currentColor" : fill} />
          ))}
        </svg>
      );
    case "aeries":
      // Aeries has no public vector mark; a lettermark in its portal blue.
      return (
        <svg viewBox="0 0 24 24" role="img" aria-label="Aeries" className={cls}>
          <rect width="24" height="24" rx="6" fill={mono ? "currentColor" : "#1F5FA8"} />
          <path
            d="M12 5.2 17.6 18.4h-2.6l-1.25-3.1H10.2l-1.25 3.1H6.4L12 5.2Zm0 4.3-1.1 3.6h2.2L12 9.5Z"
            fill={mono ? "var(--color-background)" : "#fff"}
          />
        </svg>
      );
    case "wilcox":
      // Wilcox Chargers: green and gold lettermark.
      return (
        <svg viewBox="0 0 24 24" role="img" aria-label="Wilcox High School" className={cls}>
          <rect width="24" height="24" rx="6" fill={mono ? "currentColor" : "#0B6B3A"} />
          <path
            d="M4.5 6.5h2.4l1.7 7.1 1.9-7.1h2.4l1.9 7.1 1.7-7.1h2.4L15.9 18h-2.3l-1.9-6.9L9.8 18H7.5L4.5 6.5Z"
            fill={mono ? "var(--color-background)" : "#F2C94C"}
          />
        </svg>
      );
    case "weather":
      return (
        <svg viewBox="0 0 24 24" role="img" aria-label="Weather" className={cls} fill="none">
          <path
            d="M7 18.5a4 4 0 0 1-.6-7.95A6 6 0 0 1 18 9.6a3.5 3.5 0 0 1-.5 6.9H7Z"
            stroke={mono ? "currentColor" : "#3B82F6"}
            strokeWidth="1.8"
            strokeLinejoin="round"
          />
        </svg>
      );
    case "openai":
      return (
        <svg viewBox="0 0 24 24" role="img" aria-label="OpenAI" className={cls}>
          <circle cx="12" cy="12" r="9.5" fill="none" stroke="currentColor" strokeWidth="1.8" />
          <path d="M12 6.5l4.76 2.75v5.5L12 17.5l-4.76-2.75v-5.5L12 6.5Z" fill="none" stroke="currentColor" strokeWidth="1.6" strokeLinejoin="round" />
        </svg>
      );
    default:
      return null;
  }
}
`;

writeFileSync(new URL("../src/components/os/provider-marks.tsx", import.meta.url), file);
console.log("wrote src/components/os/provider-marks.tsx");
